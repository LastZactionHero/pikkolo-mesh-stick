#!/usr/bin/env python3
"""
Pikkolo Mesh Stick Rev B — schematic source.

Generates mesh.kicad_sch. Connectivity lives here; schlib.py turns it into KiCad and
layout.py provides the drawing shapes. Regenerating overwrites the .kicad_sch, so once
you start editing in Eeschema this file becomes a reference rather than the source.

Rev B changes from Rev A:
  - USB-A edge fingers replaced by a real USB-C male plug (J2), with the Rd pull-down
    the Type-C spec requires of a sink presenting a plug. This also frees the board
    from the 2.0 mm thickness that only the USB-A fingers needed.
  - RF network, power chain and level shifter drawn as wired chains rather than as
    free-floating parts joined only by labels.

Provenance tags on nets and values:
  [variant]  verbatim from Meshtastic variants/rp2040/rp2040-lora/variant.h
  [chosen]   not in that file; needs a variant patch (see docs/SCHEMATIC-NOTES.md)
  [semtech]  SX1262 datasheet Rev 2.2 / AN1200.40 reference-design topology
  [ws]       value from the Waveshare RP2040-LoRa schematic, the board this clones
  [rpi]      Raspberry Pi "Hardware design with RP2040" minimal design
  [usbc]     USB Type-C Cable and Connector Specification
"""
