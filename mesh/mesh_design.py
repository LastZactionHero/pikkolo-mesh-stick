decouple("C10", 439.42, 40.64, "100n", "+3V3_RF", at="VDD_IN/VBAT pins 1/10/11 HF")
decouple("C11", 454.66, 40.64, "1u", "+3V3_RF", at="VBAT/VBAT_IO bulk for the PA step")
