s.net("USB_DP_C", "J2.A6")
s.net("USB_DM_C", "J2.A7")
s.no_connect("J2.B5")                      # VCONN must read above zOPEN=126k: leave open  [usbc]
# B6/B7 are absent from a USB 2.0 plug by spec (Table 3-11 note 2) and the receptacle
# already shorts A6<->B6, so do not tie them "for symmetry" -- that is a stub on a 90 ohm
# pair. SBU1/SBU2 must read >=950k, and the SuperSpeed pads must float: grounding them
# would short the host's TX/RX. All are left off the netlist on purpose.  [usbc]

