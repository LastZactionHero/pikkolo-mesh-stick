# Total VBUS-to-GND capacitance is capped at 10uF by BOTH USB 2.0 (inrush, section
# 7.2.4.1) and Type-C (Table 4-3). Budget, in uF: C15 4.7 + C27 4.7 + C41 0.1 = 9.5uF.
#
