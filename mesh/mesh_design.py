def _passive(kind, val, fp, extra=None):
    """Merge the catalogue entry for a passive into its schematic properties."""
    pkg = fp.rsplit("_", 1)[0].rsplit("_", 1)[-1]
    props = dict(PASSIVES.get((kind, val, pkg), {}))
    if extra:
        props.update(extra)
    return props


def cap(ref, x, y, val, fp=FP["C"], angle=0, props=None, **kw):
    s.place(ref, C_, x, y, value=val, footprint=fp, angle=angle,
            props=_passive("C", val, fp, props), **kw)


def res(ref, x, y, val, dnp=False, angle=0, props=None, **kw):
    s.place(ref, R_, x, y, value=val, footprint=FP["R"], dnp=dnp, angle=angle,
            props=_passive("R", val, FP["R"], props), **kw)


def ind(ref, x, y, val, angle=0, fp=None, props=None, **kw):
    fp = fp or FP["L"]
    s.place(ref, L_, x, y, value=val, footprint=fp, angle=angle,
            props=_passive("L", val, fp, props), **kw)


def flag(ref, x, y):
    s.place(ref, "power:PWR_FLAG", x, y, in_bom=False)


def rail(ref, lib, x, y):
    s.place(ref, lib, x, y, in_bom=False)


def decouple(ref, x, y, val, node, fp=FP["C"], at=None):
    """
    A bypass cap from `node` to ground, drawn vertically.

    `at` records which pin the cap belongs to. Stacked symbol pins collapse a whole
    rail onto one schematic node, so without this the layout has no way to know that
    C3..C9 are one-per-IOVDD-pin rather than six caps that may all go on one side.
    """
    cap(ref, x, y, val, fp=fp, props={"Description": "decoupling: %s" % at} if at else None)
    s.net(node, "%s.1" % ref)
    s.net("GND", "%s.2" % ref)


def series(ref, kind, x, y, val, a, b, angle=0):
    """A series element bridging nets `a` and `b`, joined only by its labels."""
    (cap if kind == "C" else ind if kind == "L" else res)(ref, x, y, val, angle=angle)
    s.net(a, "%s.1" % ref)
    s.net(b, "%s.2" % ref)


